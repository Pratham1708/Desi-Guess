GameCard _whoCard(
  String id,
  String name,
  String desc,
  String tag,
  String style, {
  required String icon,
  required int color,
  CardDifficulty difficulty = CardDifficulty.medium,
}) {
  return GameCard(
    id: id,
    name: name,
    category: GameCategory.who,
    description: desc,
    iconName: icon,
    accentHex: color,
    difficulty: difficulty,
    keywords: [name.toLowerCase(), tag.toLowerCase(), style.toLowerCase()],
    attributes: {'Specialty': tag, 'Vibe': style},
  );
}

