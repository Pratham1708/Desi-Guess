GameCard _whoCard(
  String id,
  String name,
  String desc,
  String tag,
  String era, {
  String icon = 'sparkles',
  int color = 0xFF8B5CF6,
  CardDifficulty difficulty = CardDifficulty.medium,
  List<String> extraKeywords = const [],
}) {
  return GameCard(
    id: id,
    name: name,
    category: GameCategory.who,
    description: desc,
    iconName: icon,
    accentHex: color,
    difficulty: difficulty,
    keywords: [
      name.toLowerCase(),
      tag.toLowerCase(),
      era.toLowerCase(),
      ...extraKeywords,
    ],
    attributes: {'Role': tag, 'Era': era},
  );
}

