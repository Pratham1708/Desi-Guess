GameCard _whatCard(
  String id,
  String name,
  String desc,
  String tag,
  String origin, {
  required String icon,
  required int color,
  CardDifficulty difficulty = CardDifficulty.medium,
}) {
  return GameCard(
    id: id,
    name: name,
    category: GameCategory.what,
    description: desc,
    iconName: icon,
    accentHex: color,
    difficulty: difficulty,
    keywords: [name.toLowerCase(), tag.toLowerCase(), origin.toLowerCase()],
    attributes: {'Type': tag, 'Origin': origin},
  );
}

