GameCard _whereCard(
  String id,
  String name,
  String desc,
  String region,
  String vibe, {
  required String icon,
  required int color,
  CardDifficulty difficulty = CardDifficulty.medium,
}) {
  return GameCard(
    id: id,
    name: name,
    category: GameCategory.where,
    description: desc,
    iconName: icon,
    accentHex: color,
    difficulty: difficulty,
    keywords: [name.toLowerCase(), region.toLowerCase(), vibe.toLowerCase()],
    attributes: {'Region': region, 'Known For': vibe},
  );
}

